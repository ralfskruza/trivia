const dicts: Record<Lang, Dict> = { lv, en };

type T = (key: TKey, vars?: Record<string, string | number>) => string;
const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>(null!);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('trivia:lang') as Lang) || 'lv');
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('trivia:lang', l);
    setLangState(l);
  }, []);
  const t = useCallback<T>(
    (key, vars) => {
      let s = dicts[lang][key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  return createElement(Ctx.Provider, { value: { lang, setLang, t } }, children);
}

export const useI18n = () => useContext(Ctx);

export function LangToggle() {
  const { lang, setLang } = useI18n();
  return createElement(
    'button',
    { className: 'btn ghost small', onClick: () => setLang(lang === 'lv' ? 'en' : 'lv'), title: 'Language' },
    lang === 'lv' ? 'EN' : 'LV',
  );
}

